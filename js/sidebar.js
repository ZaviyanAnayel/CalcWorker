(function () {
  "use strict";

  function normalizePath(path) {
    if (!path) return "/";
    var clean = path.split("?")[0].split("#")[0];
    if (clean === "/index.html") return "/";
    if (clean.length > 1 && clean.endsWith("/")) clean = clean.slice(0, -1);
    return clean || "/";
  }

  function escapeHtml(val) {
    return String(val)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;")
      .replace(/>/g, "&gt;").replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");
  }

  function renderSidebar() {
    var sidebarNav = document.querySelector("#sidebar .sidebar-nav") || document.querySelector(".sidebar-nav");
    if (!sidebarNav) return;

    var currentPath = normalizePath(window.location.pathname);
    var groups = window.cwSidebarGroups || [];

    var html = groups.map(function (group) {
      var hasActiveItem = group.items.some(function (item) {
        var itemPath = normalizePath(item.href);
        return (itemPath === currentPath || (itemPath !== "/" && currentPath.endsWith(itemPath)));
      });
      // Keep overview, flagship, and active category open; others can be collapsed
      var isOverviewOrFlagship = (group.title === "Overview" || group.title === "Flagship Suite");
      var collapsedClass = (currentPath !== "/" && !hasActiveItem && !isOverviewOrFlagship) ? " collapsed" : "";

      return '<div class="nav-group' + collapsedClass + '">' +
        '<div class="nav-group-title" role="button" tabindex="0" aria-expanded="' + (collapsedClass ? 'false' : 'true') + '">' + escapeHtml(group.title) + '</div>' +
        '<ul class="nav-links">' +
        group.items.map(function (item) {
          var itemPath = normalizePath(item.href);
          var isActive = (itemPath === currentPath || (itemPath !== "/" && currentPath.endsWith(itemPath)));
          var activeClass = isActive ? " active" : "";
          var badgeHtml = item.badge
            ? '<span class="nav-link-badge" style="background:' + (item.badgeType === "hot" ? "var(--brand-primary)" : "var(--brand-primary)") + ';color:#fff;">' + escapeHtml(item.badge) + '</span>'
            : "";
          return '<li>' +
            '<a href="' + escapeHtml(item.href) + '" class="nav-link' + activeClass + '" title="' + escapeHtml(item.label) + '">' +
              '<span class="nav-link-icon">' + escapeHtml(item.icon) + '</span>' +
              '<span class="nav-link-text">' + escapeHtml(item.label) + '</span>' +
              badgeHtml +
            '</a>' +
          '</li>';
        }).join("") +
        '</ul>' +
      '</div>';
    }).join("");

    sidebarNav.innerHTML = html;

    // Issue 7 Accordion Handler (Collapsible categories)
    sidebarNav.addEventListener("click", function (e) {
      var titleEl = e.target.closest(".nav-group-title");
      if (titleEl) {
        var groupEl = titleEl.closest(".nav-group");
        if (groupEl) {
          var isCollapsed = groupEl.classList.toggle("collapsed");
          titleEl.setAttribute("aria-expanded", isCollapsed ? "false" : "true");
        }
      }
    });

    sidebarNav.addEventListener("keydown", function (e) {
      if ((e.key === "Enter" || e.key === " ") && e.target.classList.contains("nav-group-title")) {
        e.preventDefault();
        e.target.click();
      }
    });

    // Bulletproof Scroll Restoration (Ensures sidebar never jumps back to top)
    var sidebarEl = document.getElementById("sidebar") || document.querySelector(".sidebar");
    if (sidebarEl) {
      var restoreScrollPos = function () {
        var activeLink = sidebarNav.querySelector(".nav-link.active");
        var saved = sessionStorage.getItem("cw_sidebar_scroll");

        if (currentPath === "/") {
          sidebarEl.scrollTop = 0;
          sessionStorage.setItem("cw_sidebar_scroll", "0");
        } else if (saved !== null && !isNaN(parseInt(saved, 10)) && parseInt(saved, 10) > 0) {
          sidebarEl.scrollTop = parseInt(saved, 10);
        } else if (activeLink) {
          var targetPos = activeLink.offsetTop - (sidebarEl.clientHeight / 2) + (activeLink.clientHeight / 2);
          sidebarEl.scrollTop = Math.max(0, targetPos);
          sessionStorage.setItem("cw_sidebar_scroll", sidebarEl.scrollTop);
        }
      };

      restoreScrollPos();
      requestAnimationFrame(restoreScrollPos);
      setTimeout(restoreScrollPos, 60);

      // Keep scroll state updated
      sidebarEl.addEventListener("scroll", function () {
        sessionStorage.setItem("cw_sidebar_scroll", sidebarEl.scrollTop);
      }, { passive: true });

      sidebarNav.addEventListener("click", function (e) {
        var link = e.target.closest("a");
        if (link) {
          if (link.getAttribute("href") === "/") {
            sessionStorage.setItem("cw_sidebar_scroll", "0");
          } else {
            sessionStorage.setItem("cw_sidebar_scroll", sidebarEl.scrollTop);
          }
        }
      });
    }
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", renderSidebar);
  } else {
    renderSidebar();
  }
})();
